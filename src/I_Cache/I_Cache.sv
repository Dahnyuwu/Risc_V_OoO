                                                                                   1'b0; 

    assign inst_1_va    =    ((inst_1 & 17'h1FFFF) == 17'b0110011_000_0000001) ? 1'b1 :
                             ((inst_1 & 17'h1FF80) == 17'b0010011_000_0000000) ? 1'b1 :
