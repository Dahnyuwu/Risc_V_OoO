                             ((inst_1 & 17'h1FFFF) == 17'b0110011_110_0000000) ? 1'b1 :
                             ((inst_1 & 17'h1FF80) == 17'b0000011_010_0000000) ? 1'b1 :
                             ((inst_1 & 17'h1FF80) == 17'b0100011_010_0000000) ? 1'b1 :
                             ((inst_1 & 17'h1FF80) == 17'b1100011_000_0000000) ? 1'b1 :
                             ((inst_1 & 17'h1FF80) == 17'b1100011_001_0000000) ? 1'b1 :
                             ((inst_1 & 17'h1FF80) == 17'b1100111_000_0000000) ? 1'b1 :
                             ((inst_1 & 17'h1FF80) == 17'b0010011_010_0000000) ? 1'b1 :
