                             ((inst_2 & 17'h1FFFF) == 17'b0010011_001_0000000) ? 1'b1 :
                             ((inst_2 & 17'h1FC00) == 17'b0110111_000_0000000) ? 1'b1 :
                                                                                   1'b0; 

    assign inst_3_va    =    ((inst_3 & 17'h1FFFF) == 17'b0110011_000_0000001) ? 1'b1 :
                             ((inst_3 & 17'h1FF80) == 17'b0010011_000_0000000) ? 1'b1 :
                             ((inst_3 & 17'h1FFFF) == 17'b0110011_000_0000000) ? 1'b1 :
                             ((inst_3 & 17'h1FF80) == 17'b0010011_111_0000000) ? 1'b1 :
                             ((inst_3 & 17'h1FFFF) == 17'b0110011_111_0000000) ? 1'b1 :
