                             ((inst_1 & 17'h1FFFF) == 17'b0010011_001_0000000) ? 1'b1 :
                             ((inst_1 & 17'h1FC00) == 17'b0110111_000_0000000) ? 1'b1 :
                                                                                   1'b0; 

